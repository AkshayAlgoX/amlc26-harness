"""Generate (never push) the Kaggle kernel directories for one exact code commit.

usage: python scripts/kaggle/make_kernels.py --commit <sha> --bundle-slug akshayalgox/<code-dataset> --out <dir>
Writes <out>/{bundle_stage,h4,test_<country>_<i>,...,merge}. bundle_stage = `git archive <commit>` without any
symlink / hard-link member (never followed, never exported) + BUNDLE_COMMIT
+ dataset-metadata.json. Each kernel dir = a stub run.py (locates the bundle under /kaggle/input/datasets, copies it,
executes scripts/kaggle/kaggle_job.py with the embedded job) + kernel-metadata.json (CPU, internet off, private).
Kernel dependency chain: h4 -> test_<country> (kernel_sources: h4) -> merge (kernel_sources: h4 + all test kernels).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import tarfile
import io
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OWNER = "akshayalgox"
OFFICIAL = f"{OWNER}/amlc26-2026-official-data-v2"
STUB = '''# AMLC26 kernel stub (generated by scripts/kaggle/make_kernels.py). All logic lives in the bundled repository.
# Finds the code bundle by CONTENT (BUNDLE_COMMIT == this job's commit) under any /kaggle/input mount layout; a
# kernel-output copy of the repo (".../amlc26-agy2") is used only if no dataset copy exists. Fails closed otherwise.
import glob, json, os, pathlib, shutil, subprocess, sys
JOB = {job}
INPUT = pathlib.Path(os.environ.get("AMLC_INPUT", "/kaggle/input"))
WORK = pathlib.Path(os.environ.get("AMLC_WORK", "/kaggle/working"))
hits = [pathlib.Path(p).parent for p in glob.glob(str(INPUT / "**" / "BUNDLE_COMMIT"), recursive=True)]
roots = sorted(h for h in hits if (h / "BUNDLE_COMMIT").read_text().strip() == JOB["bundle_commit"])
pref = [r for r in roots if r.name != "amlc26-agy2"] or roots
if len(pref) != 1:
    for p in sorted(glob.glob(str(INPUT / "*")) + glob.glob(str(INPUT / "*" / "*")) + glob.glob(str(INPUT / "*" / "*" / "*"))):
        print("input:", p)
    print("BUNDLE_COMMIT files:", [(str(h), (h / "BUNDLE_COMMIT").read_text().strip()[:12]) for h in hits])
    sys.exit("FAIL-CLOSED: code bundle for commit %s not found exactly once (%d)" % (JOB["bundle_commit"][:12], len(pref)))
repo = WORK / "amlc26-agy2"
if repo.exists():
    shutil.rmtree(repo)
shutil.copytree(pref[0], repo)
print("bundle:", pref[0], flush=True)
sys.exit(subprocess.call([sys.executable, "scripts/kaggle/kaggle_job.py", json.dumps(JOB)], cwd=repo))
'''


def kernel(out: Path, name: str, title: str, job: dict, bundle_slug: str, sources: list):
    d = out / name
    d.mkdir(parents=True, exist_ok=True)
    (d / "run.py").write_text(STUB.format(job=json.dumps(job)))
    meta = {"id": f"{OWNER}/{title}", "title": title, "code_file": "run.py", "language": "python", "kernel_type": "script",
            "is_private": True, "enable_gpu": False, "enable_tpu": False, "enable_internet": False,
            "dataset_sources": [OFFICIAL, bundle_slug], "competition_sources": [],
            "kernel_sources": [f"{OWNER}/{s}" for s in sources]}
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    return meta["id"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", required=True)
    ap.add_argument("--bundle-slug", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    commit = subprocess.check_output(["git", "rev-parse", a.commit], cwd=REPO, text=True).strip()
    out = Path(a.out)
    stage = out / "bundle_stage" / "amlc26-agy2"
    stage.mkdir(parents=True, exist_ok=True)
    tar = subprocess.check_output(["git", "archive", commit], cwd=REPO)
    tf = tarfile.open(fileobj=io.BytesIO(tar))
    members = [m for m in tf.getmembers() if not (m.issym() or m.islnk())]   # never export (local/dangling) links
    skipped = sorted(m.name for m in tf.getmembers() if m.issym() or m.islnk())
    tf.extractall(stage, members=members)
    assert not [p for p in stage.rglob("*") if p.is_symlink()], "symlink leaked into the bundle"
    (stage / "BUNDLE_COMMIT").write_text(commit + "\n")
    (out / "bundle_stage" / "dataset-metadata.json").write_text(json.dumps(
        {"title": a.bundle_slug.split("/")[1], "id": a.bundle_slug, "licenses": [{"name": "other"}]}))
    cfg_sha = hashlib.sha256((stage / "experiments/configs/h4_x2_frozen.json").read_bytes()).hexdigest()
    plan = json.loads((stage / "experiments/configs/test_shards.json").read_text())
    base = {"bundle_commit": commit, "config_sha256": cfg_sha}
    ids = {"h4": kernel(out, "h4", "amlc26-x2-h4", {**base, "kind": "h4"}, a.bundle_slug, [])}
    tests = []
    for c, n in plan["shards"].items():
        for i in range(n):
            t = f"amlc26-x2-test-{c.lower()}-{i}"
            kernel(out, f"test_{c}_{i}", t, {**base, "kind": "test_shards", "shards": {"country": c, "count": n, "indices": [i]}},
                   a.bundle_slug, ["amlc26-x2-h4"])
            tests.append(t)
    merge_sources = ["amlc26-x2-h4"] + tests
    # Kaggle hard limit: 20 dataset + kernel sources per notebook.  Merge has 2 dataset_sources + len(merge_sources) kernel_sources.
    if 2 + len(merge_sources) > 20:
        import sys; sys.exit(f"FAIL-CLOSED: merge kernel would need {2 + len(merge_sources)} sources (max 20)")
    kernel(out, "merge", "amlc26-x2-merge", {**base, "kind": "merge"}, a.bundle_slug, merge_sources)
    print(json.dumps({"commit": commit, "config_sha256": cfg_sha, "skipped_links": skipped,
                      "kernels": ["amlc26-x2-h4"] + tests + ["amlc26-x2-merge"]}))


if __name__ == "__main__":
    main()
